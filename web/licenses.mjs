// Prepends to each built script and stylesheet the published notice of every
// third-party package whose code it contains.
// Usage: plugins: [..., licenses()], worker: { plugins: () => [worker_licenses()] }
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const worker = { builds: 0, packages: new Map() };

const notice_file = /^(licen[cs]e|copying)(\.md|\.txt)?$/i;
const vite_appendix = /^# Licenses of bundled dependencies/m;

function fail(message)
{
    throw new Error(`licenses: ${message}`);
}

function normal(path)
{
    return path.split('\\').join('/');
}

function clean(text)
{
    const lines = text.replace(/\r\n/g, '\n').split('\n').map((line) => line.trimEnd());
    while (lines.length > 0 && lines[0] === '')
        lines.shift();

    while (lines.length > 0 && lines[lines.length - 1] === '')
        lines.pop();

    return lines.join('\n');
}

function package_root(path)
{
    const match = normal(path).match(/^(.*\/node_modules\/(?:@[^/]+\/)?[^/]+)\//);
    return match ? match[1] : undefined;
}

function find_package(name, from)
{
    for (let directory = from; ; directory = dirname(directory))
    {
        const root = join(directory, 'node_modules', name);
        if (existsSync(join(root, 'package.json')))
            return normal(root);

        if (dirname(directory) === directory)
            fail(`package '${name}' not found from ${from}`);
    }
}

function bare_specifier(specifier)
{
    if (specifier.startsWith('.') || specifier.startsWith('/'))
        return undefined;

    const parts = specifier.split('/');
    return specifier.startsWith('@') ? parts.slice(0, 2).join('/') : parts[0];
}

function read_package(root)
{
    return JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
}

// The leading comment of the package's main file, for packages that publish
// their notice there instead of in a license file.
function header_notice(root, manifest)
{
    const main = join(root, manifest.main ?? 'index.js');
    const lines = [];
    for (const line of readFileSync(main, 'utf8').replace(/\r\n/g, '\n').split('\n'))
    {
        if (!line.startsWith('//'))
            break;

        lines.push(line.replace(/^\/\/ ?/, '').replace(/^-+$/, ''));
    }

    const text = clean(lines.join('\n'));
    if (!/copyright/i.test(text))
        fail(`${manifest.name} has no license file and no notice in ${main}`);

    return text;
}

// The quoted license text of a dependency recorded in vite's own notice.
function vite_bundled_notice(vite, name)
{
    const text = readFileSync(join(vite, 'LICENSE.md'), 'utf8').replace(/\r\n/g, '\n');
    const lines = text.split('\n');
    const start = lines.findIndex((line) =>
        line.startsWith('## ') && line.slice(3).split(', ').includes(name));

    if (start < 0)
        fail(`${name} not found in ${vite}/LICENSE.md`);

    const quoted = [];
    for (const line of lines.slice(start + 1))
    {
        if (line.startsWith('## '))
            break;

        if (line.startsWith('>'))
            quoted.push(line.replace(/^> ?/, ''));
        else if (quoted.length > 0)
            break;
    }

    return clean(quoted.join('\n'));
}

function package_entry(root)
{
    const manifest = read_package(root);
    const file = readdirSync(root).find((name) => notice_file.test(name));
    let text = file ? readFileSync(join(root, file), 'utf8') : header_notice(root, manifest);

    if (manifest.name === 'vite')
        text = text.split(vite_appendix)[0];

    return { name: manifest.name, version: manifest.version, text: clean(text) };
}

// Code generated by the build itself rather than imported from a package.
function generated_entry(id, base)
{
    if (id.startsWith('\0vite/') || /\?worker/.test(id))
        return package_entry(find_package('vite', base));

    if (id === '\0commonjsHelpers.js')
    {
        const vite = find_package('vite', base);
        const plugin = '@rollup/plugin-commonjs';
        const version = read_package(vite).version;
        return { name: plugin, version: `bundled in vite ${version}`, text: vite_bundled_notice(vite, plugin) };
    }

    return undefined;
}

function add(entries, entry)
{
    entries.set(`${entry.name}@${entry.version}`, entry);
}

function collect_module(entries, id, base)
{
    const generated = generated_entry(id, base);
    if (generated)
    {
        add(entries, generated);
        return;
    }

    if (id.startsWith('\0') && !package_root(id.slice(1)))
        fail(`unattributed generated module ${JSON.stringify(id)}`);

    const root = package_root(id.replace(/^\0/, '').split('?')[0]);
    if (root)
        add(entries, package_entry(root));
}

// Packages reached from a stylesheet: @import and @plugin specifiers, and the
// imports of the config named by @config.
function collect_stylesheet(entries, id)
{
    const path = id.split('?')[0];
    const root = package_root(path);
    if (root)
    {
        add(entries, package_entry(root));
        return;
    }

    const source = readFileSync(path, 'utf8');
    const directory = dirname(path);
    const specifiers = [...source.matchAll(/@(?:import|plugin)\s+['"]([^'"]+)['"]/g)].map((match) => match[1]);

    for (const [, config] of source.matchAll(/@config\s+['"]([^'"]+)['"]/g))
    {
        const script = readFileSync(join(directory, config), 'utf8');
        for (const match of script.matchAll(/(?:from|import|require\()\s*['"]([^'"]+)['"]/g))
            specifiers.push(match[1]);
    }

    for (const specifier of specifiers)
    {
        const name = bare_specifier(specifier);
        if (name)
            add(entries, package_entry(find_package(name, directory)));
    }
}

function comment(entries)
{
    const groups = new Map();
    for (const entry of [...entries.values()].sort((a, b) => a.name.localeCompare(b.name)))
    {
        const names = groups.get(entry.text) ?? [];
        names.push(`${entry.name} ${entry.version}`);
        groups.set(entry.text, names);
    }

    const lines = ['/*!', ' * Third-party software contained in this file, with its published notices.'];
    for (const [text, names] of groups)
    {
        lines.push(' *', ` * ---- ${names.join(', ')} ----`, ' *');
        for (const line of text.replace(/\*\//g, '*\\/').split('\n'))
            lines.push(line ? ` * ${line}` : ' *');
    }

    lines.push(' */', '');
    return lines.join('\n');
}

function chunk_entries(chunk, base)
{
    const entries = new Map();
    const ids = Object.entries(chunk.modules)
        .filter(([, module]) => module.renderedLength > 0)
        .map(([id]) => id);

    for (const id of ids)
        collect_module(entries, id, base);

    if (ids.some((id) => /\?worker/.test(id)))
    {
        if (worker.builds === 0)
            fail(`${chunk.fileName} inlines a worker built without worker_licenses()`);

        for (const entry of worker.packages.values())
            add(entries, entry);
    }

    return entries;
}

export function licenses()
{
    let base;
    return {
        name: 'licenses',
        apply: 'build',
        enforce: 'post',
        configResolved(config)
        {
            base = config.root;
        },
        generateBundle(_, bundle)
        {
            const stylesheets = new Map();
            for (const id of this.getModuleIds())
                if (/\.css($|\?)/.test(id))
                    collect_stylesheet(stylesheets, id);

            for (const file of Object.values(bundle))
            {
                if (file.type === 'chunk')
                {
                    const entries = chunk_entries(file, base);
                    if (entries.size > 0)
                        file.code = comment(entries) + file.code;
                }
                else if (file.fileName.endsWith('.css') && stylesheets.size > 0)
                {
                    file.source = comment(stylesheets) + file.source;
                }
            }
        }
    };
}

export function worker_licenses()
{
    let base;
    return {
        name: 'worker-licenses',
        apply: 'build',
        configResolved(config)
        {
            base = config.root;
        },
        generateBundle(_, bundle)
        {
            worker.builds++;
            for (const file of Object.values(bundle))
                if (file.type === 'chunk')
                    for (const entry of chunk_entries(file, base).values())
                        add(worker.packages, entry);
        }
    };
}
